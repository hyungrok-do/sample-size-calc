#!/usr/bin/env python3
"""Validate retrieved BibTeX and build the bibliography and runtime reference table.

Install scripts/requirements-references.txt. This script is offline: it does not
invent, complete, or repair bibliographic fields. Only citation keys change.
"""
import argparse
import hashlib
import html
import json
import re
from pathlib import Path

import bibtexparser
from pylatexenc.latex2text import LatexNodes2Text

ROOT = Path(__file__).resolve().parents[1]


def plain(value):
    value = html.unescape(re.sub(r"<[^>]+>", "", value))
    return " ".join(LatexNodes2Text().latex_to_text(value).split())


def citation(fields):
    author = fields.get("author") or fields.get("editor", "")
    parts = [plain(author).replace(" and ", "; ") + " (" + fields["year"] + ").",
             plain(fields["title"]).rstrip(".") + "."]
    venue = fields.get("journal") or fields.get("booktitle")
    if venue:
        detail = plain(venue)
        if fields.get("volume"):
            detail += " " + plain(fields["volume"])
        if fields.get("number"):
            detail += "(" + plain(fields["number"]) + ")"
        if fields.get("pages"):
            detail += ", " + plain(fields["pages"])
        parts.append(detail + ".")
    elif fields.get("publisher"):
        parts.append(plain(fields["publisher"]) + ".")
    if fields.get("doi"):
        parts.append("https://doi.org/" + fields["doi"])
    return " ".join(parts)


def build():
    records = json.loads((ROOT / "references/provenance.json").read_text())
    procedures = json.loads((ROOT / "references/procedures.json").read_text())
    entries, keyed, seen_dois = {}, [], set()
    for record in records:
        key = record["key"]
        assert key not in entries, f"Duplicate key: {key}"
        path = ROOT / record["raw_file"]
        raw = path.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == record["sha256"], f"Changed raw export: {path}"
        assert record["source"] and record["export_url"].startswith("https://")
        library = bibtexparser.parse_string(raw.decode("utf-8"))
        assert not library.failed_blocks and len(library.entries) == 1, f"Invalid BibTeX: {path}"
        entry = library.entries[0]
        assert entry.key == record["original_key"]
        fields = {name.lower(): field.value for name, field in entry.fields_dict.items()}
        assert fields.get("title") and fields.get("year")
        assert fields.get("author") or fields.get("editor")
        if fields.get("doi"):
            doi = fields["doi"].lower()
            assert doi not in seen_dois, f"Duplicate DOI: {doi}"
            seen_dois.add(doi)
            if record.get("doi"):
                assert doi == record["doi"].lower(), f"Unexpected DOI in {path}"
        text, count = re.subn(r"(@\w+\s*\{\s*)" + re.escape(entry.key) + r"(?=\s*,)",
                              lambda m: m[1] + key, raw.decode("utf-8"), count=1)
        assert count == 1
        # Verify the key is the only modification to the retrieved record.
        parsed = bibtexparser.parse_string(text).entries[0]
        assert {n: f.value for n, f in parsed.fields_dict.items()} == {n: f.value for n, f in entry.fields_dict.items()}
        text = text.strip() + "\n"
        entries[key] = (citation(fields), text, record)
        keyed.append(text)
    assert len(procedures) == len({p["id"] for p in procedures})
    for proc in procedures:
        assert proc["keys"], f"No retrieved reference for {proc['id']}"
        assert len(proc["keys"]) == len(set(proc["keys"]))
        assert set(proc["keys"]) <= entries.keys(), f"Unresolved key in {proc['id']}"

    bib = "% Retrieved BibTeX. Only citation keys are namespaced.\n% See references/provenance.json for sources and raw-file SHA-256 hashes.\n\n" + "\n".join(keyed)
    cpp = ["// Generated by scripts/build_references.py. Do not edit.\n",
           "static const std::vector<Record>& records() {\n  static const std::vector<Record> value = {\n"]
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    for key, (cite, text, record) in entries.items():
        cpp.append("    {" + ", ".join(map(quote, [key, cite, text, record["source"], record["export_url"]])) + "},\n")
    cpp.append("  };\n  return value;\n}\n\nstatic const std::vector<Mapping>& mappings() {\n  static const std::vector<Mapping> value = {\n")
    for proc in procedures:
        cpp.append("    {" + quote(proc["id"]) + ", {" + ", ".join(map(quote, proc["keys"])) + "}},\n")
    cpp.append("  };\n  return value;\n}\n")
    return {ROOT / "references.bib": bib,
            ROOT / "core/src/engine/bibliography_data.inc": "".join(cpp)}, len(entries), len(procedures)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if committed outputs differ")
    args = parser.parse_args()
    outputs, nrecords, nprocedures = build()
    for path, text in outputs.items():
        if args.check:
            assert path.read_text() == text, f"Stale output: {path}; run scripts/build_references.py"
        else:
            path.write_text(text, encoding="utf-8")
    print(f"Verified {nrecords} retrieved records and {nprocedures} procedure mappings.")


if __name__ == "__main__":
    main()
