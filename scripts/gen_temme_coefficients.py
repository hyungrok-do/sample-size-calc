"""Generate the Taylor coefficients of Temme's C_n(eta) used by pgamma (gamma.cpp).

Temme's uniform asymptotic expansion of the regularized incomplete gamma
function reads

    Q(a, x) = Phi_bar(eta sqrt(a)) + exp(-a eta^2 / 2) / sqrt(2 pi a) * sum_n C_n(eta) a^-n,

with lambda = x / a and eta = sign(lambda - 1) sqrt(2 (lambda - 1 - ln lambda)).
The coefficient functions satisfy

    C_0 = 1 / (lambda - 1) - 1 / eta,
    C_n = eta^-1 dC_{n-1}/deta + (-1)^n gamma_n / (lambda - 1),

where gamma_n are the coefficients of the Stirling series
Gamma*(a) = 1 + 1/(12a) + 1/(288a^2) - ...  Each C_n is analytic at eta = 0 (the
poles of the two terms cancel, which is checked below).

mu(eta) = lambda - 1 follows from mu dmu/deta = eta (1 + mu), so its Taylor
coefficients obey a simple recurrence.  Everything is exact rational arithmetic.

Usage:  python3 scripts/gen_temme_coefficients.py > core/src/stats/temme_coefficients.inc
"""
from fractions import Fraction as F

ORDER = 60  # Taylor terms of mu(eta); C_n keeps ORDER - 1 - 2n terms
TERMS = 8   # C_0 .. C_7

STIRLING = [F(1), F(1, 12), F(1, 288), F(-139, 51840), F(-571, 2488320), F(163879, 209018880),
            F(5246819, 75246796800), F(-534703531, 902961561600)]


def coefficients():
    a = [F(0), F(1)]
    for n in range(2, ORDER + 2):
        s = sum(a[i] * (n + 1 - i) * a[n + 1 - i] for i in range(2, n))
        a.append((a[n - 1] - s) / (n + 1))
    s = a[1:]  # mu / eta
    inv = [F(1)]  # eta / mu
    for n in range(1, ORDER):
        inv.append(-sum(s[k] * inv[n - k] for k in range(1, n + 1)))
    cs = [[inv[k + 1] for k in range(ORDER - 1)]]
    for n in range(1, TERMS):
        prev = cs[-1]
        sign = 1 if n % 2 == 0 else -1
        assert prev[1] + sign * STIRLING[n] * inv[0] == 0, "pole does not cancel"
        cs.append([(m + 2) * prev[m + 2] + sign * STIRLING[n] * inv[m + 1] for m in range(len(prev) - 2)])
    return cs


def main():
    cs = coefficients()
    assert cs[0][:4] == [F(-1, 3), F(1, 12), F(-2, 135), F(1, 864)]
    assert cs[1][:3] == [F(-1, 540), F(-1, 288), F(1, 378)]
    assert cs[2][0] == F(25, 6048)
    print("// Generated by scripts/gen_temme_coefficients.py -- do not edit.")
    print("// Taylor coefficients (in eta) of Temme's C_n(eta), n = 0 .. %d." % (TERMS - 1))
    for n, c in enumerate(cs):
        body = ",\n    ".join("%.17e" % float(x) for x in c)
        print("constexpr double TEMME_C%d[%d] = {\n    %s};" % (n, len(c), body))
    print("constexpr const double* TEMME_C[%d] = {%s};" % (TERMS, ", ".join("TEMME_C%d" % n for n in range(TERMS))))
    print("constexpr int TEMME_LEN[%d] = {%s};" % (TERMS, ", ".join(str(len(c)) for c in cs)))


if __name__ == "__main__":
    main()
